#!/usr/bin/env python3
"""
Build data/pairs.js for the website from a COCO-style annotations.json.

Only pairs whose two image files exist in the images/ folder are included,
so you can add more image pairs later and simply re-run this script.

Usage (from the repository root):
    python tools/build_pairs.py
    python tools/build_pairs.py --annotations path/to/annotations.json
"""
import argparse
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--annotations", default=str(ROOT / "tools" / "annotations.json"))
    parser.add_argument("--images", default=str(ROOT / "images"))
    parser.add_argument("--out", default=str(ROOT / "data" / "pairs.js"))
    args = parser.parse_args()

    with open(args.annotations, encoding="utf-8") as f:
        data = json.load(f)

    images_dir = Path(args.images)
    images = {img["id"]: img for img in data["images"]}

    diffs_by_pair = defaultdict(list)
    for d in data.get("discrepancies", []):
        diffs_by_pair[d["pair_id"]].append(d)

    pairs = []
    skipped = 0
    for pair_id in sorted(diffs_by_pair):
        diffs = diffs_by_pair[pair_id]
        first = diffs[0]
        file_a, file_b = first["file_name_a"], first["file_name_b"]
        if not (images_dir / file_a).exists() or not (images_dir / file_b).exists():
            skipped += 1
            continue
        img_a = images.get(first["image_id_a"], {})
        pairs.append({
            "id": pair_id,
            "a": f"images/{file_a}",
            "b": f"images/{file_b}",
            "width": img_a.get("width", 128),
            "height": img_a.get("height", 128),
            "differences": [
                {
                    "type": d.get("change_type"),
                    "before": d.get("icon_name_before"),
                    "after": d.get("icon_name_after"),
                    "bbox_before": d.get("bbox_before"),
                    "bbox_after": d.get("bbox_after"),
                }
                for d in diffs
            ],
        })

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    body = "[\n" + ",\n".join("  " + json.dumps(p) for p in pairs) + "\n]"
    out.write_text(
        "// Generated by tools/build_pairs.py. Do not edit by hand; re-run the script instead.\n"
        f"window.PAIRS = {body};\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(pairs)} pairs to {out} ({skipped} pairs skipped because their images are not in {images_dir}).")


if __name__ == "__main__":
    main()
